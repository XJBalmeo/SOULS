import puppeteer from "puppeteer";
import { startServer } from "../serve.mjs";
const server = await startServer(0);
const url = "http://127.0.0.1:" + server.address().port + "/";
const browser = await puppeteer.launch({ headless: true, args: ["--autoplay-policy=no-user-gesture-required"] });
const page = await browser.newPage();
await page.setViewport({ width: 1280, height: 720 });
const logs = [];
page.on("console", (m) => { if (["error","warn","warning"].includes(m.type())) logs.push(m.type() + ": " + m.text()); });
page.on("pageerror", (e) => logs.push("pageerror: " + e.message));
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const ev = (f, a) => page.evaluate(f, a);
const scenes = () => ev(() => Object.fromEntries(["MenuScene","GameScene","PauseScene","DeathScene","ConfirmScene"].map((k) => [k, game.scene.isActive(k) ? "A" : game.scene.isPaused(k) ? "P" : game.scene.isSleeping(k) ? "S" : "-"])));
const info = () => ev(() => { const s = game.scene.getScene("GameScene"); if (!s || !s.player) return null; return { hp: s.player.getData("hp"), st: Math.round(s.player.getData("stamina")), dead: s.isDead, atk: s.isAttacking, roll: s.isRolling, ang: Math.round(s.player.angle), alpha: s.player.alpha, pp: s.physics.world.isPaused, rats: s.rats.getChildren().filter((r) => r.active && r.getData("hp") > 0).length, hbEn: s.attackHitbox.body.enable, tw: s.tweens.getTweens().length, ratsTotal: s.rats.getChildren().length }; });
const say = async (n, extra) => console.log("## " + n + " " + JSON.stringify(extra === undefined ? await info() : extra) + " scenes=" + JSON.stringify(await scenes()) + " logs=" + JSON.stringify(logs.splice(0)));
async function fresh() {
  await page.goto(url, { waitUntil: "load" });
  await ev(() => localStorage.clear());
  await page.reload({ waitUntil: "load" }); await wait(1200);
  await page.click("#fullscreen-overlay").catch(() => {}); await wait(200);
  await ev(() => game.scene.getScene("MenuScene").enterGame("new"));
  await page.waitForFunction(() => game.scene.isActive("GameScene") && game.scene.getScene("GameScene").player);
  await wait(800);
}
const hurt = (n) => ev((n) => game.scene.getScene("GameScene").takeDamage(n), n);
const waitDead = async () => { await wait(2900); };
const fsState = () => ev(() => ({ fs: !!document.fullscreenElement, ov: document.getElementById("fullscreen-overlay").style.display }));
await fresh();
await page.keyboard.down("KeyZ"); await wait(100);
await say("attacking pre", await ev(() => { const s = game.scene.getScene("GameScene"); return { atk: s.isAttacking, hb: s.attackHitbox.body.enable }; }));
await hurt(100); await page.keyboard.up("KeyZ"); await wait(100); await say("1 dead mid-attack");
await waitDead(); await say("1 after respawn");
await page.keyboard.down("KeyD"); await page.keyboard.press("KeyX"); await wait(80);
await say("roll pre", await ev(() => game.scene.getScene("GameScene").isRolling));
await hurt(100); await page.keyboard.up("KeyD"); await wait(100); await say("2 dead mid-roll");
await waitDead(); await say("2 after respawn");
await ev(() => { const s = game.scene.getScene("GameScene"); s.player.setData("hp", 20); s.takeDamage(20); s.takeDamage(20); });
await wait(100); await say("3 double dmg"); await waitDead(); await say("3 after");
await ev(() => { const s = game.scene.getScene("GameScene"); s.player.setData("knockbackUntil", s.time.now + 500); s.player.setData("hp", 20); s.takeDamage(20); });
await waitDead(); await say("3b knockback death respawn");
await hurt(100); await wait(200);
await ev(() => document.exitFullscreen().catch(() => {})); await wait(1200);
await say("4 fs exit during fall +1.4s", await fsState());
await wait(3000); await say("4 +3s more");
await page.click("#fullscreen-overlay").catch((e) => logs.push("click fail " + e.message)); await wait(3500); await say("4 after overlay click");
await hurt(100); await wait(1200); await say("5 deathscene up");
await ev(() => document.exitFullscreen().catch(() => {})); await wait(3000);
await say("5 fs exit during DeathScene +3s", await fsState());
await page.click("#fullscreen-overlay").catch((e) => logs.push("click fail " + e.message)); await wait(1500); await say("5 after overlay click");
await hurt(100); await wait(100); await page.keyboard.press("Escape"); await page.keyboard.press("KeyP"); await wait(300); await say("6 esc in fall");
await wait(1000); await page.keyboard.press("Escape"); await wait(300); await say("6 esc in DeathScene"); await wait(2500); await say("6 after");
await ev(() => { const s = game.scene.getScene("GameScene"); s.input.keyboard.emit("keydown-ESC", { repeat: false }); s.takeDamage(100); });
await wait(3500); await say("7 esc+death same frame +3.5s");
await browser.close(); server.close();
